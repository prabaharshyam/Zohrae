// Renders the film frame by frame with Playwright and muxes it with music.wav.
//   node render.mjs                     # both formats → out/zohrae-launch-{portrait,landscape}.mp4
//   node render.mjs portrait            # one format
//   node render.mjs stills 0.5,4.6,...  # PNG stills of both formats at those times (for review)
import { spawn, execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { chromium } from "playwright";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const FPS = 30;
const SIZES = { portrait: [1080, 1920], landscape: [1920, 1080] };

// The wordmark paths, shared with the website.
const ts = readFileSync(join(root, "components/brand/wordmark-paths.ts"), "utf8");
writeFileSync(
  join(here, "wordmark.js"),
  "// Generated by render.mjs from components/brand/wordmark-paths.ts\n" +
    ts.replace(/^\/\/.*$/gm, "").replace(/export const (\w+)/g, "window.$1").replace(/ as const/g, ""),
);

// Fonts from the site's build (Bodoni Moda, Jost, Pinyon Script; all SIL Open Font License).
const FONTS = {
  "bodoni.woff2": "28f82cd8566a528f-s.p.14og3_uq6yls0.woff2",
  "bodoni-italic.woff2": "10a4c8eca0b9ce81-s.p.0rrr4v4rsoo3q.woff2",
  "jost.woff2": "81cef6a21128489e-s.p.2csanl8cs02r-.woff2",
  "pinyon.woff2": "db3f01ae0719bbb0-s.2c0pkezzij_il.woff2",
};
mkdirSync(join(here, "fonts"), { recursive: true });
for (const [name, file] of Object.entries(FONTS)) {
  const src = join(root, ".next/static/media", file);
  if (!existsSync(join(here, "fonts", name)) && existsSync(src)) copyFileSync(src, join(here, "fonts", name));
}
mkdirSync(join(here, "out"), { recursive: true });

const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM || "/opt/pw-browsers/chromium",
  args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--allow-file-access-from-files"],
});

async function open(fmt) {
  const [w, h] = SIZES[fmt];
  const page = await browser.newPage({ viewport: { width: w, height: h } });
  page.on("pageerror", (e) => console.error(fmt, "pageerror:", e.message));
  page.on("console", (m) => m.type() === "error" && console.error(fmt, m.text()));
  await page.goto(pathToFileURL(join(here, "index.html")).href + `?fmt=${fmt}`);
  await page.evaluate(() => window.__ready);
  return page;
}

const mode = process.argv[2];
if (mode === "stills") {
  const times = (process.argv[3] || "1,2.3,4.7,6.2,7.8,9.3,10.5,11.9,13.2,14.2,15.5,17,19.6,21.8,24.5,28.5").split(",").map(Number);
  for (const fmt of ["portrait", "landscape"]) {
    const page = await open(fmt);
    for (const t of times) {
      await page.evaluate((t) => window.__seek(t), t);
      await page.screenshot({ path: join(here, "out", `still-${fmt}-${t.toFixed(2)}.png`) });
    }
    await page.close();
  }
} else {
  for (const fmt of mode ? [mode] : ["portrait", "landscape"]) {
    const page = await open(fmt);
    const out = join(here, "out", `zohrae-launch-${fmt}.mp4`);
    const ff = spawn("ffmpeg", [
      "-y", "-loglevel", "error",
      "-f", "image2pipe", "-framerate", String(FPS), "-c:v", "mjpeg", "-i", "-",
      "-i", join(here, "out", "music.wav"),
      "-c:v", "libx264", "-preset", "medium", "-crf", "18", "-pix_fmt", "yuv420p", "-profile:v", "high",
      "-c:a", "aac", "-b:a", "192k", "-shortest", "-movflags", "+faststart", out,
    ], { stdio: ["pipe", "inherit", "inherit"] });
    const frames = 30 * FPS;
    const t0 = Date.now();
    for (let i = 0; i < frames; i++) {
      await page.evaluate((t) => window.__seek(t), i / FPS);
      const buf = await page.screenshot({ type: "jpeg", quality: 92 });
      if (!ff.stdin.write(buf)) await new Promise((r) => ff.stdin.once("drain", r));
      if (i % 150 === 0) console.log(fmt, `frame ${i}/${frames}`, `${((Date.now() - t0) / 1000).toFixed(0)}s`);
    }
    ff.stdin.end();
    await new Promise((r) => ff.on("close", r));
    await page.close();
    console.log("wrote", out);
  }
}
await browser.close();
